-- 0020_jugadas_fijas_agrupadas.sql
-- Agrupa las combinaciones en jugadas fijas reutilizables y permite
-- asignar cada jugada a programaciones independientes.

create table if not exists public.jugadas_fijas (
  id bigint generated by default as identity primary key,
  temporada_id bigint not null references public.temporadas(id) on delete cascade,
  nombre text not null,
  juego_codigo text not null references public.juegos(codigo),
  activa boolean not null default true,
  observaciones text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint jugadas_fijas_nombre_no_vacio check (btrim(nombre) <> ''),
  constraint jugadas_fijas_temporada_nombre_key unique (temporada_id,nombre),
  constraint jugadas_fijas_identidad_temporada_juego_key unique (id,temporada_id,juego_codigo)
);

alter table public.jugadas_fijas enable row level security;

revoke all on table public.jugadas_fijas from anon,authenticated;
grant select on table public.jugadas_fijas to anon;
grant select,insert,update,delete on table public.jugadas_fijas to authenticated;
grant all privileges on table public.jugadas_fijas to service_role;
grant usage,select on sequence public.jugadas_fijas_id_seq to authenticated,service_role;

create policy jugadas_fijas_public_read
on public.jugadas_fijas
for select
to anon,authenticated
using (activa=true);

create policy jugadas_fijas_admin_insert
on public.jugadas_fijas
for insert
to authenticated
with check (
  exists (
    select 1 from public.administradores a
    where a.user_id=(select auth.uid()) and a.activo=true
  )
);

create policy jugadas_fijas_admin_update
on public.jugadas_fijas
for update
to authenticated
using (
  exists (
    select 1 from public.administradores a
    where a.user_id=(select auth.uid()) and a.activo=true
  )
)
with check (
  exists (
    select 1 from public.administradores a
    where a.user_id=(select auth.uid()) and a.activo=true
  )
);

create policy jugadas_fijas_admin_delete
on public.jugadas_fijas
for delete
to authenticated
using (
  exists (
    select 1 from public.administradores a
    where a.user_id=(select auth.uid()) and a.activo=true
  )
);

create trigger jugadas_fijas_set_updated_at
before update on public.jugadas_fijas
for each row execute function private.set_updated_at();

alter table public.combinaciones
  add column if not exists jugada_fija_id bigint,
  add column if not exists estrellas smallint[] not null default '{}'::smallint[];

alter table public.combinaciones
  drop constraint if exists combinaciones_temporada_id_numero_orden_key,
  drop constraint if exists combinaciones_seis_numeros,
  drop constraint if exists combinaciones_numeros_rango;

insert into public.jugadas_fijas(
  temporada_id,nombre,juego_codigo,activa,observaciones
)
select distinct
  c.temporada_id,
  case
    when c.juego_codigo='primitiva' then 'Combinaciones Fijas Peña Outra Máis'
    else 'Combinaciones fijas '||coalesce(j.nombre,c.juego_codigo)
  end,
  c.juego_codigo,
  true,
  'Grupo creado automáticamente a partir de las combinaciones existentes'
from public.combinaciones c
left join public.juegos j on j.codigo=c.juego_codigo
where not exists (
  select 1 from public.jugadas_fijas jf
  where jf.temporada_id=c.temporada_id
    and jf.juego_codigo=c.juego_codigo
);

update public.combinaciones c
set jugada_fija_id=jf.id
from public.jugadas_fijas jf
where c.jugada_fija_id is null
  and jf.temporada_id=c.temporada_id
  and jf.juego_codigo=c.juego_codigo;

alter table public.combinaciones
  alter column jugada_fija_id set not null;

alter table public.combinaciones
  add constraint combinaciones_jugada_fija_temporada_juego_fkey
  foreign key (jugada_fija_id,temporada_id,juego_codigo)
  references public.jugadas_fijas(id,temporada_id,juego_codigo)
  on delete cascade,
  add constraint combinaciones_jugada_fija_orden_key
  unique (jugada_fija_id,numero_orden),
  add constraint combinaciones_formato_valido
  check (
    (
      juego_codigo in ('primitiva','bonoloto')
      and cardinality(numeros)=6
      and cardinality(estrellas)=0
      and 0 < all(numeros)
      and 50 > all(numeros)
    )
    or
    (
      juego_codigo='euromillones'
      and cardinality(numeros)=5
      and cardinality(estrellas)=2
      and 0 < all(numeros)
      and 51 > all(numeros)
      and 0 < all(estrellas)
      and 13 > all(estrellas)
    )
  );

alter table public.programacion_juegos
  add column if not exists jugada_fija_id bigint
    references public.jugadas_fijas(id) on delete set null;

update public.programacion_juegos p
set jugada_fija_id=jf.id
from public.jugadas_fijas jf
where p.usar_combinaciones_fijas=true
  and p.jugada_fija_id is null
  and jf.temporada_id=p.temporada_id
  and jf.juego_codigo=p.juego_codigo;

create or replace function private.desactivar_programaciones_jugada()
returns trigger
language plpgsql
security invoker
set search_path=''
as $$
begin
  if old.activa=true and new.activa=false then
    update public.programacion_juegos
    set activa=false,updated_at=now()
    where jugada_fija_id=new.id
      and activa=true;
  end if;
  return new;
end;
$$;

create trigger jugadas_fijas_desactivar_programaciones
after update of activa on public.jugadas_fijas
for each row execute function private.desactivar_programaciones_jugada();

create or replace function private.generar_sorteos_programados(
  p_fecha date default current_date
)
returns integer
language plpgsql
security invoker
set search_path=''
as $$
declare
  p record;
  v_dia date;
  v_sorteo_id bigint;
  v_count integer := 0;
  v_combo_count integer;
  v_nombre_sorteo text;
  old_draw record;
begin
  for old_draw in
    select s.id
    from public.sorteos s
    join public.programacion_juegos pj on pj.id=s.programacion_id
    left join public.jugadas_fijas jf on jf.id=pj.jugada_fija_id
    where s.automatico=true
      and s.fecha between p_fecha and p_fecha+6
      and (
        pj.activa=false
        or not (extract(isodow from s.fecha)::smallint=any(pj.dias_semana))
        or (
          pj.usar_combinaciones_fijas=true
          and (
            pj.jugada_fija_id is null
            or coalesce(jf.activa,false)=false
          )
        )
      )
  loop
    perform public.eliminar_sorteo(old_draw.id);
  end loop;

  for p in
    select pj.*
    from public.programacion_juegos pj
    join public.temporadas t on t.id=pj.temporada_id
    where pj.activa=true and t.activa=true
  loop
    if p.usar_combinaciones_fijas and p.jugada_fija_id is null then
      raise exception 'La programación % no tiene una jugada fija seleccionada',p.nombre;
    end if;

    if p.usar_combinaciones_fijas and not exists (
      select 1
      from public.jugadas_fijas jf
      where jf.id=p.jugada_fija_id
        and jf.temporada_id=p.temporada_id
        and jf.juego_codigo=p.juego_codigo
        and jf.activa=true
    ) then
      continue;
    end if;

    for v_dia in
      select gs::date
      from generate_series(p_fecha,p_fecha+6,interval '1 day') gs
      where extract(isodow from gs)::smallint=any(p.dias_semana)
      order by gs
    loop
      v_nombre_sorteo := case
        when p.usar_combinaciones_fijas=true
          and p.juego_codigo='primitiva'
          and lower(p.nombre)='primitiva habitual'
        then null
        else p.nombre
      end;

      select s.id into v_sorteo_id
      from public.sorteos s
      where s.programacion_id=p.id and s.fecha=v_dia
      limit 1;

      if v_sorteo_id is null then
        select s.id into v_sorteo_id
        from public.sorteos s
        where s.programacion_id is null
          and s.automatico=true
          and s.juego_codigo=p.juego_codigo
          and s.fecha=v_dia
          and coalesce(s.nombre,'')=coalesce(v_nombre_sorteo,'')
        limit 1;

        if v_sorteo_id is not null then
          update public.sorteos
          set programacion_id=p.id
          where id=v_sorteo_id;
        end if;
      end if;

      if v_sorteo_id is null then
        insert into public.sorteos(
          temporada_id,juego_codigo,fecha,nombre,estado,automatico,programacion_id
        )
        values(
          p.temporada_id,p.juego_codigo,v_dia,v_nombre_sorteo,
          'pendiente',true,p.id
        )
        returning id into v_sorteo_id;
      end if;

      if p.usar_combinaciones_fijas then
        select count(*) into v_combo_count
        from public.combinaciones c
        where c.jugada_fija_id=p.jugada_fija_id
          and c.activa=true;

        if v_combo_count=0 then
          raise exception
            'La jugada fija de la programación % no tiene combinaciones activas',
            p.nombre;
        end if;

        delete from public.apuestas a
        where a.sorteo_id=v_sorteo_id
          and a.programacion_id=p.id
          and (
            a.origen_combinacion_id is null
            or not exists (
              select 1
              from public.combinaciones c
              where c.id=a.origen_combinacion_id
                and c.jugada_fija_id=p.jugada_fija_id
                and c.activa=true
            )
          );

        insert into public.apuestas(
          sorteo_id,origen_combinacion_id,programacion_id,tipo,
          descripcion,importe,fuente_fondos,datos
        )
        select
          v_sorteo_id,c.id,p.id,'fija',
          coalesce(c.nombre,'Combinación '||c.numero_orden),
          round(p.importe_total/v_combo_count,2),
          p.fuente_fondos,
          case
            when p.juego_codigo='euromillones' then
              jsonb_build_object(
                'numeros',to_jsonb(c.numeros),
                'estrellas',to_jsonb(c.estrellas),
                'codigo_millon',null
              )
            else
              jsonb_build_object(
                'numeros',to_jsonb(c.numeros),
                'reintegro',null,
                'resguardo',((c.numero_orden-1)/5)+1
              )
          end
        from public.combinaciones c
        where c.jugada_fija_id=p.jugada_fija_id
          and c.activa=true
        order by c.numero_orden
        on conflict (sorteo_id,origen_combinacion_id)
          where origen_combinacion_id is not null
        do update
          set programacion_id=excluded.programacion_id,
              descripcion=excluded.descripcion,
              importe=excluded.importe,
              fuente_fondos=excluded.fuente_fondos,
              datos=excluded.datos,
              updated_at=now();
      else
        delete from public.apuestas a
        where a.sorteo_id=v_sorteo_id
          and a.programacion_id=p.id
          and a.origen_combinacion_id is not null;

        insert into public.apuestas(
          sorteo_id,programacion_id,tipo,descripcion,importe,fuente_fondos,datos
        )
        values(
          v_sorteo_id,p.id,'programada',p.nombre,
          p.importe_total,p.fuente_fondos,p.datos_apuesta
        )
        on conflict (sorteo_id,programacion_id)
          where programacion_id is not null
            and origen_combinacion_id is null
        do update
          set descripcion=excluded.descripcion,
              importe=excluded.importe,
              fuente_fondos=excluded.fuente_fondos,
              datos=excluded.datos,
              updated_at=now();
      end if;

      v_count:=v_count+1;
    end loop;
  end loop;

  return v_count;
end;
$$;

create or replace function public.crear_temporada_preparada(
  p_anio smallint,
  p_fecha_inicio date,
  p_fecha_fin date,
  p_cuota_semanal numeric,
  p_numero_semanas smallint,
  p_copiar_combinaciones boolean default true,
  p_copiar_programaciones boolean default true,
  p_observaciones text default null
)
returns bigint
language plpgsql
security invoker
set search_path=''
as $$
declare
  v_origen_id bigint;
  v_origen_anio smallint;
  v_nueva_id bigint;
begin
  if not exists(
    select 1 from public.administradores a
    where a.user_id=(select auth.uid()) and a.activo=true
  ) then
    raise exception 'No tienes permisos para crear temporadas';
  end if;

  if p_fecha_fin < p_fecha_inicio then
    raise exception 'La fecha final no puede ser anterior a la inicial';
  end if;

  if p_cuota_semanal is null or p_cuota_semanal < 0 then
    raise exception 'La cuota semanal no es válida';
  end if;

  if p_numero_semanas is null or p_numero_semanas < 1 or p_numero_semanas > 53 then
    raise exception 'El número de semanas debe estar entre 1 y 53';
  end if;

  select t.id,t.anio into v_origen_id,v_origen_anio
  from public.temporadas t
  where t.activa=true
  limit 1;

  if v_origen_id is null then
    raise exception 'No hay una temporada activa de referencia';
  end if;

  if p_anio <= v_origen_anio then
    raise exception 'La nueva temporada debe ser posterior a la temporada activa';
  end if;

  if exists(select 1 from public.temporadas t where t.anio=p_anio) then
    raise exception 'Ya existe la temporada %',p_anio;
  end if;

  if p_copiar_programaciones
     and not p_copiar_combinaciones
     and exists(
       select 1
       from public.programacion_juegos p
       where p.temporada_id=v_origen_id
         and p.usar_combinaciones_fijas=true
     ) then
    raise exception
      'Para copiar programaciones con jugadas fijas también debes copiar las combinaciones';
  end if;

  insert into public.temporadas(
    anio,fecha_inicio,fecha_fin,cuota_semanal,numero_semanas,activa,observaciones
  )
  values(
    p_anio,p_fecha_inicio,p_fecha_fin,p_cuota_semanal,p_numero_semanas,false,
    coalesce(p_observaciones,'Temporada preparada desde '||v_origen_anio)
  )
  returning id into v_nueva_id;

  if p_copiar_combinaciones then
    insert into public.jugadas_fijas(
      temporada_id,nombre,juego_codigo,activa,observaciones
    )
    select
      v_nueva_id,jf.nombre,jf.juego_codigo,jf.activa,jf.observaciones
    from public.jugadas_fijas jf
    where jf.temporada_id=v_origen_id
    order by jf.id;

    insert into public.combinaciones(
      temporada_id,jugada_fija_id,numero_orden,nombre,
      numeros,estrellas,activa,juego_codigo
    )
    select
      v_nueva_id,jf_new.id,c.numero_orden,c.nombre,
      c.numeros,c.estrellas,c.activa,c.juego_codigo
    from public.combinaciones c
    join public.jugadas_fijas jf_old on jf_old.id=c.jugada_fija_id
    join public.jugadas_fijas jf_new
      on jf_new.temporada_id=v_nueva_id
     and jf_new.nombre=jf_old.nombre
     and jf_new.juego_codigo=jf_old.juego_codigo
    where c.temporada_id=v_origen_id
    order by jf_old.id,c.numero_orden;
  end if;

  if p_copiar_programaciones then
    insert into public.programacion_juegos(
      temporada_id,juego_codigo,activa,dias_semana,importe_por_apuesta,
      observaciones,nombre,usar_combinaciones_fijas,datos_apuesta,
      importe_total,fuente_fondos,jugada_fija_id
    )
    select
      v_nueva_id,p.juego_codigo,p.activa,p.dias_semana,p.importe_por_apuesta,
      p.observaciones,p.nombre,p.usar_combinaciones_fijas,p.datos_apuesta,
      p.importe_total,p.fuente_fondos,jf_new.id
    from public.programacion_juegos p
    left join public.jugadas_fijas jf_old on jf_old.id=p.jugada_fija_id
    left join public.jugadas_fijas jf_new
      on jf_new.temporada_id=v_nueva_id
     and jf_new.nombre=jf_old.nombre
     and jf_new.juego_codigo=jf_old.juego_codigo
    where p.temporada_id=v_origen_id
    order by p.id;
  end if;

  return v_nueva_id;
end;
$$;
